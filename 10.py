# LISTAS - Se pueden modificar (mutables)
# Se crean con corchetes []

frutas = ["manzana", "banana", "naranja"]
print(frutas) 

# Modificar elementos
frutas[0] = "fresa"
print(frutas)

# Agregar elementos
frutas.append("piña")
print(frutas)

# Eliminar elementos
frutas.remove("banana")
print(frutas)  

# Longitud
print(len(frutas))